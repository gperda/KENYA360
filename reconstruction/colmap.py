def _frame_key(value) -> str | None:
    if value is None:
        return None
    text = str(value).strip().replace("\\", "/")
    if not text:
        return None
    candidate = os.path.splitext(os.path.basename(text))[0]
    return candidate or text


def _quat_to_matrix(qw, qx, qy, qz):
    q = np.asarray([float(qw), float(qx), float(qy), float(qz)], dtype=np.float64)
    norm = np.linalg.norm(q)
    if norm == 0.0:
        raise ValueError("Quaternion has zero norm")
    q = q / norm
    qw, qx, qy, qz = q
    return np.array(
        [
            [1.0 - 2.0 * (qy * qy + qz * qz), 2.0 * (qx * qy - qz * qw), 2.0 * (qx * qz + qy * qw)],
            [2.0 * (qx * qy + qz * qw), 1.0 - 2.0 * (qx * qx + qz * qz), 2.0 * (qy * qz - qx * qw)],
            [2.0 * (qx * qz - qy * qw), 2.0 * (qy * qz + qx * qw), 1.0 - 2.0 * (qx * qx + qy * qy)],
        ],
        dtype=np.float64,
    )


class ColmapWorkflow(ReconstructionWorkflow):
    """COLMAP adapter for the rig trajectory generated by scripts/colmap_pipeline.py."""

    georeferenced = True

    def __init__(self, config):
        self.config = config
        self.trajectory_path = config.trajectory_file_path
        self.camera_matrix = self._load_camera_matrix(config)

    def _load_trajectory(self, path):
        rows = {}
        with open(path, "r", encoding="utf-8") as handle:
            for raw_line in handle:
                line = raw_line.strip()
                if not line or line.startswith("#"):
                    continue

                tokens = [token for token in line.replace(",", " ").split() if token]
                if len(tokens) < 8:
                    continue

                image_name = tokens[0]
                try:
                    tx, ty, tz, qw, qx, qy, qz = [float(value) for value in tokens[1:8]]
                except ValueError:
                    continue

                key = _frame_key(image_name)
                if key is None:
                    continue

                world_center = np.asarray([tx, ty, tz], dtype=np.float64)
                rows[key] = (world_center, _quat_to_matrix(qw, qx, qy, qz))
        return rows

