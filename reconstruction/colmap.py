    def _pose_for_frame(self, frame_index: int, frame_path: str | None):
        if frame_path:
            key = _frame_key(frame_path)
            if key in self.trajectory:
                return self.trajectory[key]

        if frame_index is not None:
            for candidate_key in (str(frame_index), f"frame_{frame_index}", f"{frame_index}.jpg"):
                if candidate_key in self.trajectory:
                    return self.trajectory[candidate_key]

            for key, pose in self.trajectory.items():
                if key.startswith(f"{frame_index}") or key.endswith(f"{frame_index}"):
                    return pose

        return None

    def reconstruct(self, config):
        project = Path("/home/ellie/cslam")

        subprocess.run(
            [
                str(project / ".venv/bin/python"),
                str(project / "cslam.py"),
                "--images", config.input_dir,
                "--config", config.reconstruction_config_path,
                "--calibration-json", config.camera_calibration,
                "--work_dir", config.colmap_dir,
                "--gnss", config.camera_reference_path,
                "--gnss_sigma", config.gnss_sigma,
                "--cameras", "FCY25030043,FCY25030053",
            ],
            cwd=project,
            check=True,
        )

        self.trajectory = self._load_trajectory(self.trajectory_path.replace('csv', 'txt'))
        if not self.trajectory:
            raise RuntimeError(f"COLMAP trajectory is empty: {self.trajectory_path}")

        refactor_trajectory_file(self.trajectory_path.replace('csv', 'txt'), self.trajectory_path)



    def project_detection(
        self,
        frame_index: int,
        frame_path: str | None,
        x_px: float,
        y_px: float,
        depth_m: float | None,
        class_name: str,
        detection_id: int | str,
        confidence: float,
    ) -> dict | None:

        
        if depth_m is None:
            return None
        distance = float(depth_m)
        if not np.isfinite(distance) or distance <= 0.0:
            return None

        pose = self._pose_for_frame(frame_index, frame_path)
        if pose is None:
            return None

        camera_center, rotation = pose
        fx, fy, cx, cy = self.camera_matrix[0, 0], self.camera_matrix[1, 1], self.camera_matrix[0, 2], self.camera_matrix[1, 2]

        if fx <= 0 or fy <= 0:
            return None

        norm_x = (float(x_px) - cx) / fx
        norm_y = (float(y_px) - cy) / fy
        ray_cam = np.asarray([norm_x, norm_y, 1.0], dtype=np.float64)
        ray_world = rotation @ ray_cam
        ray_norm = np.linalg.norm(ray_world)
        if ray_norm == 0.0 or not np.isfinite(ray_norm):
            return None

        ray_world = ray_world / ray_norm
        world_point = camera_center + ray_world * distance
        image_label = _frame_key(frame_path) if frame_path is not None else str(frame_index)



        return {
            "Image": image_label,
            "x_px": float(x_px),
            "y_px": float(y_px),
            "X": float(world_point[0]),
            "Y": float(world_point[1]),
            "Z": float(world_point[2]),
            "distance_from_camera": distance,
            "type": class_name,
            "id": detection_id,
            "confidence": float(confidence),
        }
